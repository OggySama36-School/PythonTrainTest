# ============================================================================
# 2. CHIA TRAIN / TEST  
# ============================================================================
cat_cols = ["gender", "ever_married", "work_type", "Residence_type", "smoking_status"]
scale_cols = ["age", "avg_glucose_level", "bmi"]
binary_cols = ["hypertension", "heart_disease"]
FEATURES = scale_cols + binary_cols + cat_cols

X = df[FEATURES]
y = df["stroke"]
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=TEST_SIZE, stratify=y, random_state=RANDOM_STATE)
print(f"\nTrain: {X_train.shape} (stroke={y_train.sum()}) | Test: {X_test.shape} (stroke={y_test.sum()})")


# ============================================================================
# 3. PIPELINE TIỀN XỬ LÝ DÙNG CHUNG
# ============================================================================
def make_preprocessor():
    return ColumnTransformer([
        ("num", SkPipeline([("imputer", SimpleImputer(strategy="median")),
                            ("scaler", StandardScaler())]), scale_cols),
        ("bin", "passthrough", binary_cols),
        ("cat", OneHotEncoder(handle_unknown="ignore", sparse_output=False), cat_cols),
    ])


def make_pipeline(clf, use_smote=True):
    """SMOTE nằm trong pipeline => mỗi fold của CV chỉ SMOTE phần train của fold đó."""
    steps = [("prep", make_preprocessor())]
    if use_smote:
        steps.append(("smote", SMOTE(random_state=RANDOM_STATE)))
    steps.append(("clf", clf))
    return ImbPipeline(steps)


# ============================================================================
# 4. GRIDSEARCHCV + K-FOLD CROSS-VALIDATION
# ============================================================================
param_grids = {
    "Logistic Regression": {                       # C, penalty (l1/l2)
        "clf__C": [0.01, 0.1, 1, 10],
        "clf__penalty": ["l1", "l2"],
    },
    "Random Forest": {                             # n_estimators, max_depth, min_samples_split
        "clf__n_estimators": [100, 200],
        "clf__max_depth": [5, 10, None],
        "clf__min_samples_split": [2, 5, 10],
    },
    "SVM": [                                       # kernel, C, gamma (gamma chỉ có nghĩa với rbf)
        {"clf__kernel": ["linear"], "clf__C": [0.1, 1, 10]},
        {"clf__kernel": ["rbf"], "clf__C": [0.1, 1, 10], "clf__gamma": ["scale", 0.01, 0.1]},
    ],
}
base_clfs = {
    # solver liblinear để hỗ trợ cả l1 và l2
    "Logistic Regression": LogisticRegression(solver="liblinear", max_iter=2000,
                                              random_state=RANDOM_STATE),
    "Random Forest": RandomForestClassifier(random_state=RANDOM_STATE, n_jobs=-1),
    # Khi GridSearch để probability=False cho nhanh (AUC lấy từ decision_function).
    # Sau khi chọn xong tham số sẽ bật probability=True để có xác suất cho API.
    "SVM": SVC(probability=False, random_state=RANDOM_STATE),
}

cv = StratifiedKFold(n_splits=N_FOLDS, shuffle=True, random_state=RANDOM_STATE)
scoring = {"f1": "f1", "recall": "recall", "precision": "precision", "roc_auc": "roc_auc"}

best_models, cv_rows = {}, []
print("\n" + "=" * 70)
print("4. GRIDSEARCHCV (k = %d)" % N_FOLDS)
print("=" * 70)

for name in base_clfs:
    print(f"\n>>> Tinh chỉnh: {name}")
    gs = GridSearchCV(make_pipeline(base_clfs[name]), param_grids[name], cv=cv,
                      scoring=scoring, refit="f1", n_jobs=-1)
    gs.fit(X_train, y_train)
    i = gs.best_index_

    model = gs.best_estimator_
    if name == "SVM":                                   # bật xác suất cho mô hình đã chọn
        model = clone(model).set_params(clf__probability=True).fit(X_train, y_train)
    best_models[name] = model

    cv_rows.append({
        "Model": name,
        "Best params": {k.replace("clf__", ""): v for k, v in gs.best_params_.items()},
        "CV F1": gs.cv_results_["mean_test_f1"][i],
        "CV Recall": gs.cv_results_["mean_test_recall"][i],
        "CV Precision": gs.cv_results_["mean_test_precision"][i],
        "CV AUC": gs.cv_results_["mean_test_roc_auc"][i],
    })
    print(f"   Best params: {gs.best_params_}")
    print(f"   CV F1 = {gs.cv_results_['mean_test_f1'][i]:.4f} | "
          f"CV Recall = {gs.cv_results_['mean_test_recall'][i]:.4f}")

cv_table = pd.DataFrame(cv_rows).set_index("Model")
print("\n=== KẾT QUẢ CROSS-VALIDATION (trên Train) ===")
print(cv_table.round(4).to_string())
cv_table.to_csv(f"{OUT_DIR}/cv_results.csv")

# ============================================================================
# 5. CHỌN MÔ HÌNH TỐT NHẤT - dựa trên Cross-Validation (Test chưa được dùng)
#    Ưu tiên F1, sau đó Recall, sau đó AUC
# ============================================================================
best_name = cv_table.sort_values(["CV F1", "CV Recall", "CV AUC"], ascending=False).index[0]
print(f"\n>>> MÔ HÌNH ĐƯỢC CHỌN (theo CV): {best_name}")


# ============================================================================
# 6. ĐÁNH GIÁ CUỐI CÙNG TRÊN TẬP TEST (ngưỡng 0.5, dùng 1 lần)
# ============================================================================
def evaluate(model, Xa, ya):
    prob = model.predict_proba(Xa)[:, 1]
    pred = (prob >= CLASS_THRESHOLD).astype(int)
    return {"Accuracy": accuracy_score(ya, pred),
            "Precision": precision_score(ya, pred, zero_division=0),
            "Recall": recall_score(ya, pred),
            "F1": f1_score(ya, pred),
            "AUC-ROC": roc_auc_score(ya, prob)}


# Thời gian huấn luyện: đo 1 lần fit với tham số tốt nhất (công bằng giữa các mô hình)
fit_time = {}
for name, model in best_models.items():
    t0 = time.time()
    clone(model).fit(X_train, y_train)
    fit_time[name] = time.time() - t0

test_rows, overfit_rows = [], []
for name, model in best_models.items():
    tr, te = evaluate(model, X_train, y_train), evaluate(model, X_test, y_test)
    test_rows.append({"Model": name, **te, "Thời gian fit (s)": fit_time[name]})
    overfit_rows.append({"Model": name, "Train F1": tr["F1"], "Test F1": te["F1"],
                         "Δ F1": tr["F1"] - te["F1"],
                         "Train Recall": tr["Recall"], "Test Recall": te["Recall"],
                         "Train AUC": tr["AUC-ROC"], "Test AUC": te["AUC-ROC"]})

test_table = pd.DataFrame(test_rows).set_index("Model")
overfit_table = pd.DataFrame(overfit_rows).set_index("Model")
print("\n=== KẾT QUẢ TRÊN TẬP TEST ===");               print(test_table.round(4).to_string())
print("\n=== OVERFITTING (Train vs Test) ===");          print(overfit_table.round(4).to_string())
test_table.to_csv(f"{OUT_DIR}/test_results.csv")
overfit_table.to_csv(f"{OUT_DIR}/overfitting.csv")

best_pred = (best_models[best_name].predict_proba(X_test)[:, 1] >= CLASS_THRESHOLD).astype(int)
print(f"\n=== CLASSIFICATION REPORT - {best_name} ===")
print(classification_report(y_test, best_pred, target_names=["Không đột quỵ", "Có đột quỵ"]))

