def get_risk_level(prob):
    for upper, level, emoji in RISK_BANDS:
        if prob < upper:
            return level, emoji


def predict_stroke(gender, age, hypertension, heart_disease, ever_married,
                   work_type, residence_type, avg_glucose_level, bmi,
                   smoking_status, verbose=True):
    row = pd.DataFrame([{
        "age": age, "avg_glucose_level": avg_glucose_level,
        "bmi": np.nan if bmi is None else bmi,          # bmi thiếu -> imputer (median) xử lý
        "hypertension": hypertension, "heart_disease": heart_disease,
        "gender": gender, "ever_married": ever_married, "work_type": work_type,
        "Residence_type": residence_type, "smoking_status": smoking_status,
    }])[FEATURES]
    prob = float(final_model.predict_proba(row)[0, 1])
    label = int(prob >= CLASS_THRESHOLD)
    level, emoji = get_risk_level(prob)

    if verbose:
        print("\n" + "=" * 60)
        print(f"{emoji}  KẾT QUẢ DỰ ĐOÁN NGUY CƠ ĐỘT QUỴ")
        print("=" * 60)
        print(f"  Bệnh nhân      : {gender}, {age} tuổi")
        print(f"  Điểm nguy cơ   : {prob*100:5.1f}%  (điểm của mô hình, không phải xác suất thực tế)")
        print(f"  Mức độ nguy cơ : {level}")
        print(f"  Nhãn dự đoán   : {'Có nguy cơ' if label else 'Không có nguy cơ'}")
        print("=" * 60)
    return prob, label, level, emoji


